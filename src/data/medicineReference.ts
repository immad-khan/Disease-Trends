export function findMedicine(query: string): MedicineRef | null {
  const q = query.trim().toLowerCase();
  if (!q) return null;
  return (
    MEDICINES.find((m) => m.generic.toLowerCase() === q) ??
    MEDICINES.find((m) => m.brandNames.some((b) => b.toLowerCase() === q)) ??
    MEDICINES.find((m) => m.generic.toLowerCase().includes(q) || q.includes(m.generic.toLowerCase().split(" ")[0])) ??
    MEDICINES.find((m) => m.brandNames.some((b) => b.toLowerCase().includes(q) || q.includes(b.toLowerCase()))) ??
    null
  );
}

export function searchMedicines(query: string, limit = 8): MedicineRef[] {
  const q = query.trim().toLowerCase();
  if (!q) return MEDICINES.slice(0, limit);
  return MEDICINES.filter(
    (m) =>
      m.generic.toLowerCase().includes(q) ||
      m.brandNames.some((b) => b.toLowerCase().includes(q))
  ).slice(0, limit);
}
